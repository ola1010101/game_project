#include "levels.h"

std::pair<int, int> BuiltinLevels::load(Grid& grid, int levelNum) 
{
    std::vector<std::string> custom;

    switch (levelNum) {
    case 1: custom = {
        "####################",
        "#O                 #",
        "# ##### ##### #### #",
        "# #     ##    ##   #",
        "# #   #  ###       #",
        "# # # #  #  ## ##  #",
        "# # # # # # # #    #",
        "# # # # # # # # #  #",
        "# # # #  ###  ##   #",
        "#   #   #   #   #  #",
        "########### #####  #",
        "#                 X#",
        "####################"
    }; break;
    case 2: custom = {
        "#####################",
        "#O    #             #",
        "#     #     #       #",
        "##### ##### ####### #",
        "#     #     #       #",
        "#     #             #",
        "##### ##### ####### #",
        "#     #     #       #",
        "#           #       #",
        "################# ###",
        "#                 X #",
        "#####################"
    }; break;
    case 3: custom = {
        "#####################",
        "#O#   #   #   #   # #",
        "# # # # # # # # #   #",
        "# # # # # # # # #   #",
        "# # # # # # # # # # #",
        "#   #   #   #   #   #",
        "# # # # # # # # # # #",
        "# # # # # # # # #   #",
        "# # # # # # # # # # #",
        "#   #   #   #   #   #",
        "##### # # ##### # # #",
        "#       # #       X #",
        "#####################"
    }; break;
    case 4: custom = {
        "####################",
        "#O                 #",
        "# ################ #",
        "# #                #",
        "##  ################",
        "##                 #",
        "##  # ##############",
        "#####              #",
        "##### ##############",
        "##  #              #",
        "##  ############## #",
        "#                  #",
        "# ##################",
        "#                 X#",
        "#####################"
    }; break;
    case 5: custom = {
        "#####################",
        "#O    # #      #  # #",
        "##### #     #     # #",
        "#     # #   #  #  # #",
        "####    #   #  #    #",
        "#       #  ##  ##   #",
        "#  #######   #   #  #",
        "#  #     #   #      #",
        "#  #  #  #   ### #  #",
        "#        #   #   #  #",
        "#  ######  # ### ####",
        "#         ##      X #",
        "#####################"
    }; break;
    default:
        return std::make_pair(1, 1);
    }

    grid.cells = custom;

    int hx = 1, hy = 1;
    for (int y = 0; y < (int)grid.cells.size(); ++y)
        for (int x = 0; x < (int)grid.cells[y].size(); ++x)
        {
            if (grid.cells[y][x] == 'O') {
                hx = x; hy = y;
                grid.cells[y][x] = ' ';
            }
            if (grid.cells[y][x] == 'X') grid.cells[y][x] = 'E';
        }
    return std::make_pair(hx, hy);
}